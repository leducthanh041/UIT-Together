'use strict';
const assert=require('assert');
const clock=require('../src/assets/js/conference-clock.js');
const data=require('../src/data/conferences.json').conferences;
const now=Date.parse('2026-10-10T08:00:00Z');
const nearest=clock.nextDeadline(data,now);
assert.equal(nearest.conference.id,'ecir');
assert.equal(nearest.deadline.date,'2026-10-12');
assert.equal(nearest.clock.precision,'calendar');
assert.equal(clock.nextEvent(data,now).conference.id,'acmmm');
const aoe=clock.deadlineTime({date:'2026-11-16',zone:'AoE'});
assert.equal(new Date(aoe.time).toISOString(),'2026-11-17T11:59:59.000Z');
assert.equal(aoe.precision,'aoe-day');
assert(clock.vietnamTime(aoe.time,'en').includes('18:59:59'));
const exact=clock.deadlineTime({at:'2027-01-31T23:59:59-12:00'});
assert.equal(new Date(exact.time).toISOString(),'2027-02-01T11:59:59.000Z');
assert.equal(exact.precision,'exact');
const old={id:'iccv',year:2025,cadence:2,starts_on:'2025-10-19',ends_on:'2025-10-23',location:'Old City',deadlines:[{date:'2025-03-01'}],notes_en:'Old edition',series_url:'https://iccv.thecvf.com/'};
const next=clock.edition(old,now);
assert.equal(next.year,2027);assert.equal(next.location,'');assert.equal(next.ends_on,null);assert.deepEqual(next.deadlines,[]);assert.equal(next.date_status,'unannounced');assert(!next.notes_en.includes('Old edition'));
assert.equal(old.location,'Old City');
assert.strictEqual(clock.edition(old,Date.parse('2025-10-24T11:59:58Z')),old);
assert.deepEqual(clock.parts(now+90061000,now),['01','01','01','01']);
assert.deepEqual(clock.parts(now-1,now),['00','00','00','00']);
assert.equal(clock.deadlineTime({date:'not-a-date'}),null);
assert.equal(clock.deadlineTime({date:'2026-11-32',zone:'AoE'}),null);
assert.equal(clock.nextDeadline([],now),null);
assert.equal(clock.nextEvent([],now),null);
assert.equal(clock.nextDeadline(data,Date.parse('2026-10-13T08:00:00Z')).conference.id,'cvpr');
console.log('Conference clock: deadline priority, Vietnam time, precision, rollover and expiry passed');
